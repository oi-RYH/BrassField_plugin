"""
GUI 숫자 아이템 그림 (강화석 상점 구매 버튼 +1·+10·+64 표시용). 16x16.
숫자 왼쪽에 작은 "+"(3x3)를 외곽선 한 줄을 같이 쓰며 붙인다.
두 자리는 오른쪽 정렬(숫자 끝 외곽선이 오른쪽 끝 칸), 한 자리는 "+"와 숫자 사이 줄이 칸 가운데(x=7).
굵은 5x8 픽셀 숫자를 황동색으로 칠한다: 획의 윗면은 밝게, 아랫면·오른쪽 면은 어둡게(왼쪽 위 광원), 짙은 외곽선.
색은 강화석 아이콘(tools/hud/draw_stones24.py)의 황동·외곽선 색.

사용: python3 tools/gui/make_numbers.py <textures/item 폴더> [숫자 ...]   (기본: 1 10 64)
"""
import os
import sys

from PIL import Image

O = (48, 26, 14, 255)
HI, MID, LO = (251, 202, 88, 255), (242, 146, 26, 255), (201, 96, 12, 255)

FONT = {
    "0": ["01110", "11011", "11011", "11011", "11011", "11011", "11011", "01110"],
    "1": ["00110", "01110", "11110", "00110", "00110", "00110", "00110", "11111"],
    "2": ["01110", "11011", "00011", "00110", "01100", "11000", "11000", "11111"],
    "3": ["11110", "00011", "00011", "01110", "00011", "00011", "00011", "11110"],
    "4": ["00011", "00111", "01111", "11011", "11111", "00011", "00011", "00011"],
    "5": ["11111", "11000", "11000", "11110", "00011", "00011", "11011", "01110"],
    "6": ["01110", "11000", "11000", "11110", "11011", "11011", "11011", "01110"],
    "7": ["11111", "00011", "00011", "00110", "00110", "01100", "01100", "01100"],
    "8": ["01110", "11011", "11011", "01110", "11011", "11011", "11011", "01110"],
    "9": ["01110", "11011", "11011", "11011", "01111", "00011", "00011", "01110"],
}


def draw(text, plus=True):
    w = 6 * len(text) - 1
    x0, y0 = 15 - w, (16 - 8) // 2                       # 오른쪽 정렬: 숫자 x0..14, 외곽선 15
    if len(text) == 1:
        x0 = 8                                           # "+"(4..6) · 사이 줄(7) · 숫자(8..12)
    on = set()
    for i, ch in enumerate(text):
        for y, row in enumerate(FONT[ch]):
            for x, c in enumerate(row):
                if c == "1":
                    on.add((x0 + i * 6 + x, y0 + y))
    if plus:                                             # "+" 가운데 칸: 숫자 왼쪽 외곽선 한 줄 건너
        px, py = x0 - 3, y0 + 4
        on |= {(px, py - 1), (px - 1, py), (px, py), (px + 1, py), (px, py + 1)}
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    for x, y in on:
        if (x, y - 1) not in on:
            col = HI                                     # 윗면
        elif (x, y + 1) not in on or (x + 1, y) not in on:
            col = LO                                     # 아랫면·오른쪽 면
        else:
            col = MID
        img.putpixel((x, y), col)
    for y in range(16):
        for x in range(16):
            if (x, y) not in on and any((x + i, y + j) in on for i, j in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                img.putpixel((x, y), O)
    return img


if __name__ == "__main__":
    out = sys.argv[1]
    for n in sys.argv[2:] or ["1", "10", "64"]:
        draw(n).save(os.path.join(out, "number_%s.png" % n))   # 그림은 "+n", 파일 이름은 number_n
    print("ok")
